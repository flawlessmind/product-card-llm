import json

TITLE_MAX = 70
DESC_MIN, DESC_MAX = 800, 1200

RESULT_SCHEMA = {
    "type": "object",
    "properties": {
        "seo_title": {"type": "string"},
        "seo_description": {"type": "string"},
        "search_queries": {"type": "array", "items": {"type": "string"}},
        "suitable_for": {"type": "array", "items": {"type": "string"}},
        "tasks": {"type": "array", "items": {"type": "string"}},
    },
    "required": ["seo_title", "seo_description", "search_queries", "suitable_for", "tasks"],
}

SYSTEM_PROMPT = f"""Ты — контент-редактор B2B-магазина контрольно-измерительных приборов. \
Тебе дают данные о приборе в JSON, ты готовишь черновик карточки товара на русском языке.

Жёсткие правила:
1. Используй ТОЛЬКО факты из входных данных. Любое число, единицу измерения, марку, \
стандарт, сертификат, материал, срок службы, гарантию, цену и область применения бери \
только оттуда. Ничего не додумывай и не «угадывай по типу прибора».
2. Если для какого-то пункта данных нет, не придумывай, а пиши «данных нет».
3. Не переписывай значения характеристик: числа и единицы копируй как есть.
4. Без рекламных клише и преувеличений («лучший», «уникальный», «надёжный»).
5. Не оценивай и не сравнивай характеристики. Запрещены утверждения вида «стандартный», \
«распространённый», «соответствует требованиям/стандартам», «обеспечивает удобство», \
если этого нет во входных данных.
6. Каждый факт упоминай один раз, без повторов и пересказов своими словами. \
Если фактов мало, пиши короче и не растягивай текст до верхней границы.

Что нужно вернуть (JSON):
- seo_title: заголовок до {TITLE_MAX} символов: название и тип прибора, \
по возможности — ключевая характеристика.
- seo_description: связный текст {DESC_MIN}–{DESC_MAX} символов (считай пробелы): \
назначение, использование, ключевые характеристики, производитель. \
Только то, что есть во входных данных.
- search_queries: 3–5 коротких поисковых запросов, которые ввёл бы покупатель \
(тип прибора, производитель, ключевые параметры из данных).
- suitable_for: кому подходит прибор: отрасли, специалисты или объекты, прямо названные \
во входных данных (до 4 пунктов). Если не названы — ["данных нет"].
- tasks: какие задачи решает прибор (2–4 пункта), только по входным данным. \
Иначе — ["данных нет"].

Список характеристик собирается отдельно, таблицей в seo_description его дублировать не нужно. \
Верни только JSON."""


def build_messages(product: dict) -> list[dict]:
    payload = json.dumps(product, ensure_ascii=False, indent=2)
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": f"Данные о приборе:\n{payload}"},
    ]
